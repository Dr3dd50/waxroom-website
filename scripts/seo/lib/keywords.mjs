// Pure helpers for the keyword volume study (keywords.test.mjs covers them).

export const normalize = (k) => k.toLowerCase().trim().replace(/\s+/g, ' ');

/**
 * Every term with every modifier ("" means the bare term), deduplicated.
 * Each keyword keeps the page (and proposed page) of the first group that lists it.
 */
export function buildKeywords({ groups, modifiers }) {
  const seen = new Map();
  for (const g of groups) {
    for (const term of g.terms) {
      for (const modifier of modifiers) {
        const keyword = normalize(modifier ? `${term} ${modifier}` : term);
        if (!seen.has(keyword)) seen.set(keyword, { keyword, term: normalize(term), modifier, page: g.page, proposed: g.proposed ?? null });
      }
    }
  }
  return [...seen.values()];
}

/** Pages a keyword group names that the site does not have. `exists(slug)` answers for one slug. */
export const unknownPages = (groups, exists) => [...new Set(groups.map((g) => g.page))].filter((p) => !exists(p));

/** Join API results onto our keyword list. Google returns keywords lowercased; it can drop some entirely. */
export function mergeVolumes(keywords, results) {
  const byKeyword = new Map(results.map((r) => [normalize(r.keyword), r]));
  return keywords.map((k) => {
    const r = byKeyword.get(k.keyword);
    return { ...k, volume: r?.search_volume ?? null, cpc: r?.cpc ?? null, competition: r?.competition ?? null };
  });
}

const sum = (rows) => rows.reduce((s, r) => s + (r.volume ?? 0), 0);
const fmt = (n) => (n == null ? '–' : n.toLocaleString('en-US'));

/** Markdown report: totals per page and per proposed page, then every keyword with volume. */
export function renderKeywordReport({ date, location, rows }) {
  const lines = [`# Keyword volumes: ${date}`, ''];
  lines.push(
    `Average monthly Google searches over the last 12 months, for ${location}, from Google Ads via DataForSEO. ` +
      'Generated by `npm run seo:keywords`; the raw data is in `seo/data/keyword-volumes.json`. ' +
      '`–` means Google reports no data, which usually means very few searches.',
    '',
  );

  const buckets = new Map();
  for (const r of rows) {
    const key = r.proposed ? `${r.page} → proposed /services/${r.proposed}/` : r.page;
    if (!buckets.has(key)) buckets.set(key, []);
    buckets.get(key).push(r);
  }
  const ordered = [...buckets.entries()].sort((a, b) => sum(b[1]) - sum(a[1]));

  lines.push('## Searches per month by page', '', '| Page | Searches/mo | Biggest keyword |', '|---|---|---|');
  for (const [key, rs] of ordered) {
    const top = [...rs].sort((a, b) => (b.volume ?? 0) - (a.volume ?? 0))[0];
    lines.push(`| ${key} | ${fmt(sum(rs))} | ${top.volume ? `${top.keyword} (${fmt(top.volume)})` : '–'} |`);
  }
  lines.push('');

  for (const [key, rs] of ordered) {
    const withVolume = rs.filter((r) => r.volume).sort((a, b) => b.volume - a.volume);
    lines.push(`## ${key}`, '');
    if (!withVolume.length) {
      lines.push('No keyword here has reported search volume.', '');
      continue;
    }
    lines.push('| Keyword | Searches/mo | CPC | Competition |', '|---|---|---|---|');
    for (const r of withVolume) lines.push(`| ${r.keyword} | ${fmt(r.volume)} | ${r.cpc != null ? `$${r.cpc.toFixed(2)}` : '–'} | ${r.competition ?? '–'} |`);
    const silent = rs.length - withVolume.length;
    if (silent) lines.push('', `Plus ${silent} variants with no reported volume.`);
    lines.push('');
  }
  return lines.join('\n');
}
