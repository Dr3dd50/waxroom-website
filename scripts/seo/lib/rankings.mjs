// Pure helpers for the rank tracker: grid geometry, finding our listing in a
// result page, and summarising and rendering a run. No network here, so it is
// all unit-tested (rankings.test.mjs).

const KM_PER_DEG_LAT = 110.574;
const round7 = (n) => Math.round(n * 1e7) / 1e7;

/**
 * A size x size grid of points centred on `center`, `spacingKm` apart.
 * Row 0 is the northernmost row and column 0 the westernmost, so printing rows
 * in order draws the grid the way a map shows it.
 */
export function gridPoints(center, size, spacingKm) {
  if (!Number.isInteger(size) || size < 1 || size % 2 === 0) throw new Error(`Grid size must be an odd number, got ${size}.`);
  const half = (size - 1) / 2;
  const kmPerDegLng = 111.32 * Math.cos((center.lat * Math.PI) / 180);
  const points = [];
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) {
      const northKm = (half - row) * spacingKm;
      const eastKm = (col - half) * spacingKm;
      points.push({ row, col, lat: round7(center.lat + northKm / KM_PER_DEG_LAT), lng: round7(center.lng + eastKm / kmPerDegLng) });
    }
  }
  return points;
}

export const bareDomain = (d) => (d ?? '').toLowerCase().replace(/^www\./, '');

/** Is this result item our business? Matched on Google place ID, CID, or website domain. */
export function isUs(item, us) {
  if (us.placeId && item.place_id === us.placeId) return true;
  if (us.cid && item.cid && String(item.cid) === String(us.cid)) return true;
  return Boolean(item.domain) && bareDomain(item.domain) === bareDomain(us.domain);
}

/** Our position (1-based) among Google Maps listings, or null when we are not in the results. */
export function mapsRank(items, us) {
  const listings = (items ?? []).filter((i) => i.type === 'maps_search');
  const hit = listings.find((i) => isUs(i, us));
  return hit ? hit.rank_group : null;
}

/** The listings ranked above us (or the top `n` when we are absent): who we are losing to. */
export function mapsCompetitors(items, us, n = 3) {
  const ours = mapsRank(items, us);
  return (items ?? [])
    .filter((i) => i.type === 'maps_search' && !isUs(i, us) && (ours == null || i.rank_group < ours))
    .slice(0, n)
    .map((i) => ({ title: i.title, rank: i.rank_group, rating: i.rating?.value ?? null, reviews: i.rating?.votes_count ?? null, category: i.category ?? null }));
}

/** What an ordinary Google search shows for a keyword: our organic spot, the map pack, AI Overview. */
export function organicSummary(items, us) {
  items = items ?? [];
  const organic = items.filter((i) => i.type === 'organic');
  const ours = organic.find((i) => isUs(i, us));
  const packItems = items.filter((i) => i.type === 'local_pack');
  const packHit = packItems.find((i) => isUs(i, us));
  return {
    organicRank: ours ? ours.rank_group : null,
    organicUrl: ours?.url ?? null,
    hasLocalPack: packItems.length > 0,
    localPackRank: packHit ? packHit.rank_group : null,
    hasAiOverview: items.some((i) => i.type === 'ai_overview'),
    topDomains: organic.slice(0, 5).map((i) => bareDomain(i.domain)),
  };
}

/**
 * Summary of one keyword on one grid. `depth` is how many listings were
 * fetched; a point where we are missing counts as depth + 1 in the average so
 * that dropping out of the results reads as worse, not as "no data".
 */
export function summarizeGrid(ranks, depth) {
  const found = ranks.filter((r) => r != null);
  const avg = ranks.reduce((s, r) => s + (r ?? depth + 1), 0) / ranks.length;
  return {
    points: ranks.length,
    found: found.length,
    top3: found.filter((r) => r <= 3).length,
    avgRank: Math.round(avg * 10) / 10,
  };
}

/** The grid as rows of ranks, north at the top; '--' where we are not in the results. */
export function renderGrid(ranks, size) {
  const cell = (r) => (r == null ? '--' : String(r)).padStart(3);
  const rows = [];
  for (let row = 0; row < size; row++) rows.push(ranks.slice(row * size, row * size + size).map(cell).join(''));
  return rows.join('\n');
}

const delta = (now, before) => {
  if (before == null) return '';
  const d = Math.round((before - now) * 10) / 10; // lower rank is better, so a drop in number is a gain
  if (d === 0) return ' (no change)';
  return d > 0 ? ` (▲ ${d})` : ` (▼ ${-d})`;
};

/** Markdown report for a run, with movement against the previous run when there is one. */
export function renderReport(run, previous) {
  const lines = [];
  const { config } = run;
  lines.push(`# Search rankings: ${run.date}`, '');
  lines.push(
    `Where The Wax Room shows up on Google Maps and in Google search. Generated by \`npm run seo:rankings\`; ` +
      `the raw results are in \`seo/data/rankings/${run.date}.json\`. Cost of this run: $${run.cost.toFixed(3)}.`,
    '',
  );
  lines.push('**How to read the grids:** each number is our position in the Google Maps results for someone searching from that spot (north at the top, the studio in the middle). `--` means we are not in the top ' + config.mapsDepth + '. Avg rank counts `--` as ' + (config.mapsDepth + 1) + '.', '');

  for (const grid of run.grids) {
    const prevGrid = previous?.grids?.find((g) => g.name === grid.name);
    lines.push(`## Google Maps: ${grid.label}`, '');
    lines.push('| Keyword | Avg rank | Top 3 at | Found at |', '|---|---|---|---|');
    for (const k of grid.keywords) {
      const before = prevGrid?.keywords.find((p) => p.keyword === k.keyword)?.summary.avgRank;
      const s = k.summary;
      lines.push(`| ${k.keyword} | ${s.avgRank}${delta(s.avgRank, before)} | ${s.top3}/${s.points} | ${s.found}/${s.points} |`);
    }
    lines.push('');
    for (const k of grid.keywords) {
      lines.push(`<details><summary><b>${k.keyword}</b>: avg ${k.summary.avgRank}, top 3 at ${k.summary.top3}/${k.summary.points} points</summary>`, '');
      lines.push('```', renderGrid(k.ranks, grid.size), '```', '');
      if (k.competitors.length) {
        lines.push(k.rankAtStudio == null ? 'Top listings at the studio (we are not in them):' : 'Ahead of us at the studio:', '');
        for (const c of k.competitors) {
          const rating = c.rating != null ? ` ${c.rating}★ (${c.reviews ?? 0} reviews)` : '';
          lines.push(`- #${c.rank} ${c.title}${rating}${c.category ? `, ${c.category}` : ''}`);
        }
        lines.push('');
      }
      lines.push('</details>', '');
    }
  }

  if (run.organic.length) {
    const prevOrganic = previous?.organic ?? [];
    lines.push('## Google search (from the studio)', '');
    lines.push('| Keyword | Our organic rank | Our spot in the map pack | AI Overview | Top results |', '|---|---|---|---|---|');
    for (const o of run.organic) {
      const before = prevOrganic.find((p) => p.keyword === o.keyword)?.organicRank;
      const rank = o.organicRank == null ? `not in top ${config.organicDepth}` : `${o.organicRank}${before != null ? delta(o.organicRank, before) : ''}`;
      const pack = !o.hasLocalPack ? 'no map pack' : o.localPackRank == null ? 'not in pack' : `#${o.localPackRank}`;
      lines.push(`| ${o.keyword} | ${rank} | ${pack} | ${o.hasAiOverview ? 'yes' : 'no'} | ${o.topDomains.slice(0, 3).join(', ')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
